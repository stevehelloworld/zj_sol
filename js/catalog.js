  const byId = Object.create(null);
  PROBLEMS.forEach((p, i) => {
    if (byId[p.id]) throw new Error("duplicate problem " + p.id);
    byId[p.id] = p;
    p._i = i;
    p._hay = [p.id, p.title, p.blurb, p.ask, p.idea, p.unit, ...(p.tags || []), ...(p.aliases || [])]
      .join(" ")
      .toLowerCase();
  });

  const unitName = Object.fromEntries(UNITS.map((u) => [u.id, u.name]));

  function tokensOf(q) {
    return String(q || "")
      .toLowerCase()
      .trim()
      .split(/[\s,，、]+/)
      .filter(Boolean);
  }

  function isProblemId(id) {
    return /^[a-z][0-9]{3}$/i.test(String(id || "").trim());
  }

  function get(id) {
    return byId[String(id || "").toLowerCase()] || null;
  }

  function illustrated(id) {
    return !!(window.Lessons && window.Lessons[id]);
  }

  function matchesFilter(p, filter) {
    if (!filter || filter === "all") return true;
    if (filter === "illustrated") return illustrated(p.id);
    const f = FILTERS.find((x) => x.id === filter);
    if (!f) return true;
    if (f.units) return f.units.includes(p.unit);
    return true;
  }

  function score(p, toks) {
    if (!toks.length) return 1;
    const id = p.id;
    let s = 0;
    for (const t of toks) {
      if (id === t) s += 100;
      else if (id.startsWith(t)) s += 40;
      else if (p.title.toLowerCase().includes(t)) s += 20;
      else if ((p.tags || []).some((tag) => tag.toLowerCase().includes(t))) s += 12;
      else if ((p.aliases || []).some((a) => a.toLowerCase().includes(t))) s += 16;
      else if (p._hay.includes(t)) s += 6;
      else return 0;
    }
    if (illustrated(id)) s += 3;
    return s;
  }

  function search(query, filter) {
    const toks = tokensOf(query);
    const out = [];
    for (const p of PROBLEMS) {
      if (!matchesFilter(p, filter)) continue;
      const sc = score(p, toks);
      if (sc > 0) out.push({ p, sc });
    }
    if (toks.length) out.sort((a, b) => b.sc - a.sc || a.p._i - b.p._i);
    return out.map((x) => x.p);
  }

  function grouped(list) {
    const map = new Map(UNITS.map((u) => [u.id, []]));
    for (const p of list) {
      if (!map.has(p.unit)) map.set(p.unit, []);
      map.get(p.unit).push(p);
    }
    return UNITS.map((u) => ({ unit: u, items: map.get(u.id) || [] })).filter((g) => g.items.length);
  }

